# Independent sample, arithmetic, survey-inference, coding, and package checks.
source(file.path(dirname(normalizePath(sub("^--file=","",grep("^--file=",commandArgs(),value=TRUE)[1]))),"00_setup.R"))
read_result <- function(name) read.csv(file.path(root,"Validation",paste0(name,".csv")),stringsAsFactors=FALSE)
checks <- list()
check <- function(name,ok) checks[[length(checks)+1]] <<- data.frame(check=name,pass=isTRUE(ok))
full <- readRDS(file.path(root,"Validation","full_design.rds")); primary <- subset(full,final_case); d <- primary$variables
c <- read_result("model_coefficients"); flow <- read_result("participant_flow")
check("Fresh XPT source records reconcile",sum(read_result("raw_data_manifest")$records)==flow$retained_n[1])
check("Flow decreases and exclusions reconcile",all(diff(flow$retained_n)<=0) && all(-diff(flow$retained_n)==flow$excluded_n[-1]))
check("Primary sample matches stated sample",nrow(d)==1382 && sum(d$uncontrolled)==339)
check("Complete primary outcome exposures and covariates",all(complete.cases(d[c("uncontrolled",hardships,health)])))
check("Primary design was subset from full population",nrow(full$variables)==flow$retained_n[3] && nrow(full$variables)>nrow(d))
check("Pooled weights are annual weights divided by four",max(abs(full$variables$pooled_weight-full$variables[["_LLCPWT"]]/4))==0)
for(v in hardships) {
  raw_name <- c(bills="SDHBILLS",transport="SDHTRNSP",utility="SDHUTILS")[[v]]
  check(paste("Raw to derived coding",v),identical(full$variables[[v]],yes_no(full$variables[[raw_name]])))
  z <- read_result("descriptive_results"); z <- z[z$variable==v,]
  check(paste("Group denominators and events",v),sum(z$group_n)==nrow(d) && sum(z$pain_n)==sum(d$uncontrolled))
  p0<-z$pain_percent[z$category==0]/100;p1<-z$pain_percent[z$category==1]/100
  crude<-c$OR[c$model==paste("Crude",v) & c$term==v]
  check(paste("Crude OR agrees with weighted group odds",v),abs(crude-(p1/(1-p1))/(p0/(1-p0)))<1e-7)
}
check("Distinct hardship margins verified",sum(d$transport)==175 && sum(d$utility)==183 && !identical(d$transport,d$utility))
check("Every logistic model converged",all(c$converged) && all(is.finite(c$OR)))
check("Every logistic model reports positive residual design df",all(c$residual_df>0))
check("Logistic ORs match coefficients",max(abs(exp(c$log_OR)-c$OR))<1e-7)
q<-qt(.975,c$residual_df)
check("Logistic CIs reproduce survey t inference",max(abs(exp(c$log_OR-q*c$SE)-c$lower))<1e-7 && max(abs(exp(c$log_OR+q*c$SE)-c$upper))<1e-7)
check("Primary excludes year and uses 25 parameters",all(c$parameters[c$model=="Primary"]==25) && !any(grepl("year",c$formula[c$model=="Primary"])))
check("Intermediate model uses collapsed age and income",sum(c$model=="Age sex income")==9)
check("Three separately adjusted hardship models",all(paste("Separate",hardships) %in% c$model))
check("Four leave-one-year-out models",all(paste("Omit",2022:2025) %in% c$model))
check("Missing-income category adds otherwise complete respondents",all(c$n[c$model=="Missing income retained"]==1640) && all(c$events[c$model=="Missing income retained"]==400))
check("Cancer model comparison holds restricted sample fixed",identical(unique(c$n[c$model=="Cancer subset baseline"]),unique(c$n[c$model=="Cancer covariates added"])))
check("All valid cancer-type codes 1 through 30 are retained",identical(!is.na(d$cancer_type),d$CNCRTYP2 %in% 1:30))
check("Cancer codes 28 through 30 map to Other",all(as.character(d$cancer_type[d$CNCRTYP2 %in% 28:30])=="Other"))
check("All three skin-cancer codes map to Skin",all(as.character(d$cancer_type[d$CNCRTYP2 %in% c(16,22,23)])=="Skin"))
expected_cancer <- d$CNCRTYP2 %in% 1:30 & complete.cases(d[c("active_treatment","since_diagnosis")])
check("Cancer-model sample agrees with independent raw-code eligibility",all(c$n[c$model %in% c("Cancer subset baseline","Cancer covariates added")]==sum(expected_cancer)) &&
  all(c$events[c$model %in% c("Cancer subset baseline","Cancer covariates added")]==sum(d$uncontrolled[expected_cancer])))
included <- read_result("included_excluded")
check("Included-excluded comparison uses requested 1847 base",all(included$n[included$variable=="uncontrolled" & included$included]==1382) && all(included$n[included$variable=="uncontrolled" & !included$included]==465))
missing <- read_result("missingness")
check("Missingness uses the current-pain eligible denominator",all(missing$n==1965) && all(missing$missing_n>=0 & missing$missing_n<=missing$n))
four<-read_result("four_pain_categories")
check("Four pain categories exhaust each group",all(abs(aggregate(percent~variable+hardship,four,sum)$percent-100)<1e-8))
check("Four category counts exhaust each group",all(aggregate(count~variable+hardship,four,sum)$count==aggregate(n~variable+hardship,four,max)$n))
multi<-read_result("multinomial_coefficients"); md<-read_result("multinomial_diagnostics")
check("Multinomial converges with score near zero",md$value[1]==1 && md$value[2]<.001)
check("Multinomial analytic Hessian agrees with finite difference",md$value[3]<.001)
check("Multinomial probabilities sum to one",md$value[4]<1e-12)
check("Multinomial binary coefficients reproduce survey glm",md$value[5]<1e-5)
check("Multinomial score variance reproduces binary survey variance",md$value[6]<1e-6)
check("Multinomial categories match uncontrolled events",sum(unique(multi[c("outcome","category_n")])$category_n)==339)
m<-readRDS(file.path(root,"Validation","multinomial_fit.rds"))
check("Multinomial covariance is symmetric and positive",max(abs(m$variance-t(m$variance)))<1e-7 && min(eigen(m$variance,symmetric=TRUE,only.values=TRUE)$values)>0)
allowed<-c("haven","dplyr","purrr","readr","ggplot2","tibble","survey","scales")
files<-list.files(script_dir,"[.]R$",full.names=TRUE)
text<-paste(unlist(lapply(files,readLines,warn=FALSE)),collapse="\n")
namespaced<-regmatches(text,gregexpr("[A-Za-z][A-Za-z0-9.]*::",text))[[1]]
namespaced<-sub("::$","",namespaced)
libraries<-regmatches(text,gregexpr("library\\([A-Za-z][A-Za-z0-9.]*\\)",text))[[1]]
libraries<-sub("library\\((.*)\\)","\\1",libraries)
direct<-sort(unique(c(namespaced,libraries)))
base_packages<-rownames(installed.packages(priority=c("base","recommended")))
check("Only manuscript-listed add-on packages are called",all(direct %in% c(allowed,base_packages)))
save_csv(data.frame(package=direct,allowed=direct %in% c(allowed,base_packages)),"package_audit")
used_addons <- intersect(allowed,direct)
save_csv(data.frame(package=used_addons,version=sapply(used_addons,function(p)as.character(packageVersion(p)))),"package_versions")
manifest<-read_result("publication_manifest")
check("Four main and fifteen supplementary tables exist",nrow(manifest)==19 && all(file.exists(file.path(root,"Tables + Supplementaries",paste0(manifest$id,".csv")))))
check("All five figures have PNG PDF and TIFF files",all(file.exists(file.path(root,"Figures",paste0(rep(c("Figure_1","Figure_2","Figure_3","Figure_4","Figure_S1"),each=3),rep(c(".png",".pdf",".tiff"),5))))))
result<-do.call(rbind,checks);save_csv(result,"validation_checks")
cat(sum(result$pass),"of",nrow(result),"validation checks passed\n")
if(!all(result$pass)) {print(result[!result$pass,]);stop("Validation failed")}
